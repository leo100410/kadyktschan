"""PDF phase 2 blockout: World Partition map with DEM terrain, OSM roads/river and one box per building.

Run (editor, not commandlet, because it creates and saves a level):
  UnrealEditor <project>.uproject -ExecutePythonScript="tools/editor/build_blockout.py" -unattended
(UE 5.8 on macOS 27 crashes in Slate teardown when the editor quits; data is saved before that.)
Re-running replaces the map. Inputs are generated by tools/research/*.py; values marked ANNAHME there.
Writes a report next to this script (build_blockout_report.txt) and quits the editor.
"""
import json, math, os, traceback
import unreal

ROOT = unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir())
MAP = "/Game/Kadykchan/Maps/Kadykchan_World"
TERRAIN_DIR = "/Game/Kadykchan/Maps/Terrain"
DATA = os.path.join(ROOT, "design/research/data/blockout-2026-11-07.json")
REPORT = os.path.join(ROOT, "tools/editor/build_blockout_report.txt")
CUBE = "/Engine/BasicShapes/Cube"  # 100 cm cube, pivot at centre
LENINA_COURTYARD = ("PLA_Lenina_7", "PLA_Lenina_8")

log_lines = []
def log(msg):
    log_lines.append(str(msg)); unreal.log_warning("BLOCKOUT " + str(msg))

def ue(east_m, north_m, z_m):
    # Project axes: UE +X = north, +Y = east, 1 uu = 1 cm (PDF V3)
    return unreal.Vector(north_m * 100.0, east_m * 100.0, z_m * 100.0)

def import_obj(filename, name):
    task = unreal.AssetImportTask()
    task.filename = os.path.join(ROOT, filename)
    task.destination_path = TERRAIN_DIR
    task.destination_name = name
    task.automated = True
    task.replace_existing = True
    task.save = True
    unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks([task])
    paths = list(task.imported_object_paths)
    meshes = [unreal.load_asset(p) for p in paths]
    meshes = [m for m in meshes if isinstance(m, unreal.StaticMesh)]
    if not meshes:
        raise RuntimeError("import produced no StaticMesh for %s (got %s)" % (filename, paths))
    mesh = meshes[0]
    # walkable: the blockout terrain is one big triangle mesh, so collide against its triangles
    sms = unreal.get_editor_subsystem(unreal.StaticMeshEditorSubsystem)
    log("  section 0 collision before: %s, nanite: %s" % (sms.is_section_collision_enabled(mesh, 0, 0), sms.get_nanite_settings(mesh).get_editor_property("enabled")))
    for section in range(mesh.get_num_sections(0)):
        sms.enable_section_collision(mesh, True, 0, section)
    # terrain/ribbons are coarse blockout meshes; plain (non-Nanite) render data keeps complex collision simple
    nanite = sms.get_nanite_settings(mesh); nanite.set_editor_property("enabled", False)
    sms.set_nanite_settings(mesh, nanite, True)
    body = mesh.get_editor_property("body_setup")
    body.set_editor_property("collision_trace_flag", unreal.CollisionTraceFlag.CTF_USE_COMPLEX_AS_SIMPLE)
    unreal.EditorAssetLibrary.save_loaded_asset(mesh)
    box = mesh.get_bounding_box()
    log("imported %s -> %s bounds min=%s max=%s" % (filename, mesh.get_path_name(), box.min, box.max))
    return mesh

def place(eas, asset, loc, yaw=0.0, scale=None, label=None, folder=None):
    actor = eas.spawn_actor_from_object(asset, loc, unreal.Rotator(roll=0.0, pitch=0.0, yaw=yaw))
    if scale is not None: actor.set_actor_scale3d(scale)
    if label: actor.set_actor_label(label)
    if folder: actor.set_folder_path(folder)
    # shortcut: blockout actors are always loaded (World Partition would otherwise leave them unloaded in the
    # editor and stream the terrain in after the player spawns); switch to spatial loading + HLOD in production
    actor.set_editor_property("is_spatially_loaded", False)
    return actor

def spawn_class(eas, cls, loc, label, folder="Lighting", rot=None):
    actor = eas.spawn_actor_from_class(cls, loc, rot or unreal.Rotator(roll=0.0, pitch=0.0, yaw=0.0))
    actor.set_actor_label(label); actor.set_folder_path(folder)
    return actor

def main():
    data = json.load(open(DATA, encoding="utf-8"))
    les = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
    eas = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
    if unreal.EditorAssetLibrary.does_asset_exist(MAP):
        unreal.EditorAssetLibrary.delete_asset(MAP)
    if not les.new_level(MAP, True):
        raise RuntimeError("new_level failed for " + MAP)
    log("created partitioned level " + MAP)

    terrain = import_obj("assets/terrain/terrain_kadykchan_8km.obj", "SM_Terrain_Blockout")
    roads = import_obj("assets/terrain/roads_kadykchan.obj", "SM_Roads_Blockout")
    rivers = import_obj("assets/terrain/rivers_kadykchan.obj", "SM_Rivers_Blockout")
    # UE 5.8 OBJ import keeps OBJ x and z but negates y, so mesh space is (east, -north, up);
    # yaw 90 maps it onto the project axes (+X north, +Y east). Verified via import bounds 2026-11-07.
    for mesh, mi_name in ((terrain, "MI_Ground_Tundra"), (roads, "MI_Ground_Gravel"), (rivers, "MI_Ground_River")):
        mi = unreal.load_asset("/Game/Kadykchan/Materials/" + mi_name)
        if mi:  # created by build_materials.py; without it the meshes keep the default material
            mesh.set_material(0, mi)
            unreal.EditorAssetLibrary.save_loaded_asset(mesh)
    for mesh, label in ((terrain, "Terrain_Blockout"), (roads, "Roads_Blockout"), (rivers, "River_Kadykchan_Blockout")):
        place(eas, mesh, unreal.Vector(0, 0, 0), yaw=90.0, label=label, folder="Terrain")

    cube = unreal.load_asset(CUBE)
    by_label = {}
    for b in data["buildings"]:
        z = b["ground_m"] + b["height_m"] / 2
        # long axis direction (east, north) = (cos a, sin a) -> UE yaw measured from +X(north) toward +Y(east)
        yaw = 90.0 - b["axis_deg_from_east"]
        place(eas, cube, ue(b["east_m"], b["north_m"], z), yaw=yaw,
              scale=unreal.Vector(b["length_m"], b["width_m"], b["height_m"]), label=b["label"], folder=b["folder"])
        by_label[b["label"]] = b
    log("placed %d buildings" % len(data["buildings"]))

    # Sky and light (PDF V7): summer 2011, flat white-night sun from the north-north-west
    spawn_class(eas, unreal.DirectionalLight, unreal.Vector(0, 0, 5000), "Sun", rot=unreal.Rotator(roll=0.0, pitch=-12.0, yaw=160.0))
    spawn_class(eas, unreal.SkyAtmosphere, unreal.Vector(0, 0, 0), "SkyAtmosphere")
    spawn_class(eas, unreal.SkyLight, unreal.Vector(0, 0, 3000), "SkyLight")
    spawn_class(eas, unreal.ExponentialHeightFog, unreal.Vector(0, 0, 0), "HeightFog")
    spawn_class(eas, unreal.VolumetricCloud, unreal.Vector(0, 0, 0), "VolumetricCloud")
    # Post-process per briefing V7 / art bible 2: exposure, slight vignette, film grain - no colour grading
    ppv = spawn_class(eas, unreal.PostProcessVolume, unreal.Vector(0, 0, 0), "PostProcess_Global")
    ppv.set_editor_property("unbound", True)
    pps = ppv.get_editor_property("settings")
    for key, value in (("auto_exposure_bias", -1.0), ("vignette_intensity", 0.25), ("film_grain_intensity", 0.12)):
        pps.set_editor_property("override_" + key, True)
        pps.set_editor_property(key, value)
    ppv.set_editor_property("settings", pps)
    for a in eas.get_all_level_actors():
        if isinstance(a, unreal.DirectionalLight):
            a.light_component.set_editor_property("atmosphere_sun_light", True)
        if isinstance(a, unreal.SkyLight):
            a.light_component.set_editor_property("real_time_capture", True)
            a.light_component.set_editor_property("mobility", unreal.ComponentMobility.MOVABLE)

    # Sky cycle (day -> white night, art bible 2): data asset + actor driving the sun; the sun must be movable
    sun = [a for a in eas.get_all_level_actors() if isinstance(a, unreal.DirectionalLight)][0]
    sun.light_component.set_editor_property("mobility", unreal.ComponentMobility.MOVABLE)
    da_path = "/Game/Kadykchan/Gameplay/DA_SkyCycle"
    da = unreal.load_asset(da_path) if unreal.EditorAssetLibrary.does_asset_exist(da_path) else None
    if da is None:
        factory = unreal.DataAssetFactory()
        factory.set_editor_property("data_asset_class", unreal.KdkSkyCycleSettings)
        da = unreal.AssetToolsHelpers.get_asset_tools().create_asset("DA_SkyCycle", "/Game/Kadykchan/Gameplay", None, factory)
        unreal.EditorAssetLibrary.save_loaded_asset(da)
    cycle = spawn_class(eas, unreal.KdkSkyCycleActor, unreal.Vector(0, 0, 6000), "SkyCycle")
    cycle.set_editor_property("settings", da)
    cycle.set_editor_property("sun", sun)
    log("sky cycle: %s driving %s" % (da.get_path_name(), sun.get_actor_label()))

    # Player start in the courtyard between ул. Ленина 7 and 8, looking at No. 8
    b7, b8 = by_label[LENINA_COURTYARD[0]], by_label[LENINA_COURTYARD[1]]
    ce, cn = (b7["east_m"] + b8["east_m"]) / 2 - 25.0, (b7["north_m"] + b8["north_m"]) / 2 - 10.0
    look = math.degrees(math.atan2(b8["east_m"] - ce, b8["north_m"] - cn))
    spawn_class(eas, unreal.PlayerStart, ue(ce, cn, max(b7["ground_m"], b8["ground_m"]) + 3.0), "PlayerStart_LeninaCourtyard",
                folder="Gameplay", rot=unreal.Rotator(roll=0.0, pitch=0.0, yaw=look))

    unreal.EditorLoadingAndSavingUtils.save_dirty_packages(True, True)
    log("saved")

try:
    main()
    log("RESULT OK")
except Exception:
    log("RESULT FAILED\n" + traceback.format_exc())
finally:
    open(REPORT, "w", encoding="utf-8").write("\n".join(log_lines) + "\n")
    unreal.SystemLibrary.quit_editor()
